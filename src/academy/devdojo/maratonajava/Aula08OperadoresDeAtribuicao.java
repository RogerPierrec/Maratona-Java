package academy.devdojo.maratonajava;

public class Aula08OperadoresDeAtribuicao {
    public static void main(String[] args) {
        // Operadores de Atribuição:   =  +=  -=  *=  /=  %=

        double bonus = 1800;
        bonus += 2000;
        bonus -= 1000;
        bonus *= 2;
        bonus /= 2;
        bonus %= 2;
        System.out.println(bonus);

        //
        int contador = 0;
        contador ++;
        contador --;
        System.out.println(++contador);

    }
}
